import esbuild from "esbuild";
import esbuildSvelte from "esbuild-svelte";
import fs from "fs";
import { builtinModules } from "node:module";
import path from "path";
import process from "process";
import { reloadPlugin } from "./reload-plugin.mjs";
import { sveltePreprocess } from "svelte-preprocess";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const rebuildPlugin = {
	name: "rebuild-handler",
	setup(build) {
		build.onEnd(async (result) => {
			// never push a broken bundle into the vault
			if (result.errors.length > 0) return;

			try {
				await fs.promises.copyFile(
					path.join(path.resolve(), "manifest.json"),
					path.join(path.resolve(), "dist", "manifest.json")
				);
			} catch (err) {}

			// esbuild names the CSS bundle after the entry point (main.css);
			// Obsidian loads styles.css
			try {
				await fs.promises.rename(
					path.join(path.resolve(), "dist", "main.css"),
					path.join(path.resolve(), "dist", "styles.css")
				);
			} catch (err) {
				if (err.code !== "ENOENT") throw err;
			}

			// the manifest has to be in place before Obsidian re-reads it
			await reloadPlugin();
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	// Svelte component libraries (e.g. @humanspeak/svelte-virtual-list) only
	// export their source under the "svelte" condition
	conditions: ["svelte", "browser", prod ? "production" : "development"],
	mainFields: ["svelte", "browser", "module", "main"],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "dist/main.js",
	minify: prod,
	plugins: [
		rebuildPlugin,
		esbuildSvelte({
			compilerOptions: {
				// component styles are bundled into dist/styles.css
				css: "external",
			},
			preprocess: sveltePreprocess(),
			// compiler warnings in third-party components aren't actionable here
			filterWarnings: (warning) => !warning.filename?.includes("node_modules"),
		}),
	],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
